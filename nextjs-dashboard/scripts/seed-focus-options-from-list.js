/**
 * Generate SQL seed for course_focus_options from the Course or Focus list (markdown).
 * Reads docs/courses-with-instructors.md (lines like "- ACCT305 ... - Dr X Only").
 * Outputs focus_label exactly as listed (with instructor), and course_code when present.
 *
 * Run from nextjs-dashboard root: node scripts/seed-focus-options-from-list.js
 * Then run database/seed-course-focus-options-from-list.sql in Supabase SQL Editor.
 */

const fs = require('fs')
const path = require('path')

const MD_PATH = path.join(__dirname, '..', 'docs', 'courses-with-instructors.md')
const OUT_PATH = path.join(__dirname, '..', 'database', 'seed-course-focus-options-from-list.sql')

function escapeSql(s) {
  return (s || '').replace(/'/g, "''")
}

function courseCodeFromLabel(label) {
  const m = String(label).trim().match(/^([A-Z]{2,}[0-9]+)\s/)
  return m ? m[1] : null
}

function main() {
  const content = fs.readFileSync(MD_PATH, 'utf8')
  const lines = content.split(/\r?\n/)

  const labels = []
  for (const line of lines) {
    const trimmed = line.trim()
    if (trimmed.startsWith('- ')) {
      labels.push(trimmed.slice(2).trim())
    }
  }

  // Add focus-only options that appear in tutor focuses
  for (const extra of ['INTERVIEW', 'Visual Body Software']) {
    if (!labels.includes(extra)) labels.push(extra)
  }

  // Dedupe while preserving order
  const seen = new Set()
  const uniqueLabels = labels.filter((l) => {
    const key = l.trim()
    if (!key) return false
    if (seen.has(key)) return false
    seen.add(key)
    return true
  })

  const valuesList = uniqueLabels.map((label) => {
    const code = courseCodeFromLabel(label)
    return `  (${code ? `'${escapeSql(code)}'` : 'NULL'}::varchar, '${escapeSql(label)}'::varchar)`
  })

  const sql = `-- Course/Focus options (with instructors) for Course or Focus dropdown.
-- Generated by: node scripts/seed-focus-options-from-list.js
-- Run in Supabase SQL Editor. Re-run is safe (skips existing by focus_label).

INSERT INTO course_focus_options (course_code, focus_label, active)
SELECT v.code, v.label, true
FROM (VALUES
${valuesList.join(',\n')}
) AS v(code, label)
WHERE NOT EXISTS (
  SELECT 1 FROM course_focus_options o WHERE o.focus_label = v.label
);
`

  fs.writeFileSync(OUT_PATH, sql, 'utf8')
  console.log('Wrote', uniqueLabels.length, 'focus options to', OUT_PATH)
}

main()

