/**
 * Generate SQL seed for courses table from the Course or Focus list (markdown).
 * Reads docs/courses-with-instructors.md (lines like "- ACCT305 ... - Dr X Only").
 * Outputs one row per course: course_code (e.g. ACCT305) and course_name = title only (no instructor).
 * Run from nextjs-dashboard root: node scripts/seed-courses-from-list.js
 * Then run database/seed-course-focus-from-list.sql in Supabase SQL Editor.
 */

const fs = require('fs')
const path = require('path')

const MD_PATH = path.join(__dirname, '..', 'docs', 'courses-with-instructors.md')
const OUT_PATH = path.join(__dirname, '..', 'database', 'seed-course-focus-from-list.sql')

function escapeSql(s) {
  return (s || '').replace(/'/g, "''")
}

// Parse "CODE Title - Instructor Only" -> { code, title } or { code: null, title } for no-code lines
function parseLine(line) {
  let s = line.trim()
  if (s.endsWith(' Only')) s = s.slice(0, -5).trim()
  const dashIdx = s.lastIndexOf(' - ')
  const left = dashIdx >= 0 ? s.slice(0, dashIdx).trim() : s
  const codeMatch = left.match(/^([A-Z]{2,}\d+)\s/)
  if (codeMatch) {
    const code = codeMatch[1]
    const title = left.slice(code.length).trim()
    return { code, title }
  }
  return { code: null, title: left || s }
}

function main() {
  const content = fs.readFileSync(MD_PATH, 'utf8')
  const lines = content.split(/\r?\n/)

  // One row per course: key by course_code (or course_name when code is null)
  const byCode = new Map()
  const noCodeNames = new Set()

  for (const line of lines) {
    const trimmed = line.trim()
    if (!trimmed.startsWith('- ')) continue
    const raw = trimmed.slice(2).trim()
    const { code, title } = parseLine(raw)
    if (code) {
      if (!byCode.has(code)) byCode.set(code, title)
    } else if (title && !noCodeNames.has(title)) {
      noCodeNames.add(title)
    }
  }

  const rows = []
  for (const [code, title] of byCode) {
    rows.push({ code, title })
  }
  for (const title of noCodeNames) {
    rows.push({ code: null, title })
  }

  // Focus-only options that tutors use (may not appear in markdown)
  for (const name of ['INTERVIEW', 'Visual Body Software']) {
    if (!noCodeNames.has(name) && !rows.some((r) => r.title === name)) {
      rows.push({ code: null, title: name })
    }
  }

  const valuesList = rows.map((r) => {
    const escTitle = escapeSql(r.title)
    return `  (${r.code !== null ? `'${escapeSql(r.code)}'` : 'NULL'}::varchar, '${escTitle}'::varchar)`
  })

  const sql = `-- Courses: one row per course (course_code + course_name only; no instructors).
-- Generated by: node scripts/seed-courses-from-list.js
-- Run in Supabase SQL Editor. Re-run is safe (skips existing by course_code or course_name).

INSERT INTO courses (course_code, course_name, active)
SELECT v.code, v.name, true
FROM (VALUES
${valuesList.join(',\n')}
) AS v(code, name)
WHERE NOT EXISTS (
  SELECT 1 FROM courses c
  WHERE (v.code IS NOT NULL AND c.course_code = v.code)
     OR (v.code IS NULL AND c.course_name = v.name)
);
`

  fs.writeFileSync(OUT_PATH, sql, 'utf8')
  console.log('Wrote', rows.length, 'unique courses (code + title only) to', OUT_PATH)
}

main()
