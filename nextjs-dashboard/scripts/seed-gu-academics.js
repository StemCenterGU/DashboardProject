/**
 * Generate SQL seeds for GU courses and faculty from ONE combined file (STEM dashboard).
 * Reads database/gu-academics-raw.txt:
 *   - First section (until a line containing "---" or "FACULTY") = courses (comma-delimited).
 *   - Second section = faculty (comma-delimited).
 * Run from nextjs-dashboard root: node scripts/seed-gu-academics.js
 * Then run database/seed-gu-courses.sql and database/seed-gu-faculty.sql in Supabase.
 */

const fs = require('fs')
const path = require('path')

const DATA_DIR = path.join(__dirname, '..', 'database')
const INPUT_PATH = path.join(DATA_DIR, 'gu-academics-raw.txt')
const OUT_COURSES = path.join(DATA_DIR, 'seed-gu-courses.sql')
const OUT_FACULTY = path.join(DATA_DIR, 'seed-gu-faculty.sql')

const SEPARATOR = /^\s*---|FACULTY\s*---/i

function parseCourses(raw) {
  if (!raw || !raw.trim()) return []
  return raw
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((item) => {
      const match = item.match(/^([A-Z0-9_]+)\s*\((.+)\)\s*$/)
      if (match) return { code: match[1].trim(), name: match[2].trim().replace(/'/g, "''") }
      return { code: item.replace(/'/g, "''"), name: item.replace(/'/g, "''") }
    })
}

function parseFaculty(raw) {
  if (!raw || !raw.trim()) return []
  return raw
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((item) => {
      const match = item.match(/^(.+?)\s*\(([^)]*)\)\s*:\s*(\S+)\s*$/)
      if (match) {
        return {
          name: match[1].trim().replace(/'/g, "''"),
          department: match[2].trim().replace(/'/g, "''"),
          userId: match[3].trim(),
        }
      }
      return { name: item.replace(/'/g, "''"), department: '', userId: '' }
    })
}

function main() {
  let content
  try {
    content = fs.readFileSync(INPUT_PATH, 'utf8')
  } catch (e) {
    console.error('Missing', INPUT_PATH)
    console.error('Create gu-academics-raw.txt with:')
    console.error('  Line 1 (or block above ---): courses, comma-delimited, e.g. ACCT_313 (Accounting Information Systems),...')
    console.error('  A line with --- or ---FACULTY---')
    console.error('  Next line (or block): faculty, comma-delimited, e.g. Name (Dept): USERID,...')
    process.exit(1)
  }

  const lines = content.split(/\r?\n/)
  let coursesRaw = ''
  let facultyRaw = ''
  let foundSeparator = false

  for (const line of lines) {
    if (SEPARATOR.test(line)) {
      foundSeparator = true
      continue
    }
    const t = line.trim()
    if (!t) continue
    if (foundSeparator) {
      facultyRaw += (facultyRaw ? ',' : '') + t
    } else {
      coursesRaw += (coursesRaw ? ',' : '') + t
    }
  }

  // If no separator, assume first line = courses, second line = faculty
  if (!foundSeparator && lines.length >= 2) {
    coursesRaw = lines[0].trim()
    facultyRaw = lines.slice(1).join(' ').trim()
  } else if (!foundSeparator) {
    coursesRaw = content.trim()
  }

  const courses = parseCourses(coursesRaw)
  const faculty = parseFaculty(facultyRaw)
  console.log('Parsed', courses.length, 'courses and', faculty.length, 'faculty.')

  if (courses.length > 0) {
    const courseLines = courses.map((c) => `  ('${c.code}', '${c.name}', true)`)
    const sql = `-- GU courses seed (generated by scripts/seed-gu-academics.js)
INSERT INTO courses (course_code, course_name, active)
VALUES
${courseLines.join(',\n')}
ON CONFLICT (course_code) DO UPDATE SET
  course_name = EXCLUDED.course_name,
  active = EXCLUDED.active,
  updated_at = NOW();
`
    fs.writeFileSync(OUT_COURSES, sql)
    console.log('Wrote', OUT_COURSES)
  }

  if (faculty.length > 0) {
    const facultyLines = faculty.map(
      (f) => `  ('${f.name}', ${f.department ? `'${f.department}'` : 'NULL'}, ${f.userId ? `'${f.userId}'` : 'NULL'})`
    )
    const sql = `-- GU faculty seed (generated by scripts/seed-gu-academics.js)
-- Run migration-gu-faculty.sql first if faculty table does not exist.
INSERT INTO faculty (name, department, user_id)
VALUES
${facultyLines.join(',\n')}
ON CONFLICT (user_id) DO UPDATE SET
  name = EXCLUDED.name,
  department = EXCLUDED.department,
  updated_at = NOW();
`
    fs.writeFileSync(OUT_FACULTY, sql)
    console.log('Wrote', OUT_FACULTY)
  }

  console.log('Run the .sql files in Supabase SQL Editor to load data.')
}

main()
