// Parse instructor from focus: "CODE Title - Dr X" -> "Dr X"; "INTERVIEW" -> "any instructors"
function instructorFromFocus(focus) {
  const s = focus.trim()
  const idx = s.lastIndexOf(' - ')
  if (idx >= 0) return s.slice(idx + 3).trim()
  return 'any instructors'
}

function main() {
  const tutors = Object.keys(tutorFocuses)
  const pairs = []
  for (const tutor of tutors) {
    for (const focus of tutorFocuses[tutor]) {
      if (focus.trim()) {
        pairs.push({
          tutor,
          focus: focus.trim(),
          instructor: instructorFromFocus(focus),
        })
      }
    }
  }

  const tutorInserts = tutors.map((t) => `  ('${escapeSql(t)}')`).join(',\n')
  const pairValues = pairs
    .map(
      (p) =>
        `  ('${escapeSql(p.tutor)}'::varchar, '${escapeSql(p.focus)}'::varchar, '${escapeSql(p.instructor)}'::varchar)`
    )
    .join(',\n')

  const sql = `-- Tutor–course (focus) links for STEM Center tutors (bulk), with instructor per link.
-- Generated by: node scripts/seed-tutor-focuses-bulk.js
-- Run in Supabase after migration-tutor-courses.sql, migration-tutor-courses-instructor.sql, and courses table is populated.
-- Matches focus to course by course_code or course_name; instructor is parsed from focus (text after " - ").

-- 1) Ensure all tutors exist
INSERT INTO tutors (tutor_name)
VALUES
${tutorInserts}
ON CONFLICT (tutor_name) DO NOTHING;

-- 2) Link tutors to courses with instructor (match by course_code from focus, or course_name for non-code focuses)
INSERT INTO tutor_courses (tutor_id, course_id, instructor)
SELECT t.tutor_id, c.course_id, v.instructor
FROM (VALUES
${pairValues}
) AS v(tutor_name, focus, instructor)
JOIN tutors t ON t.tutor_name = v.tutor_name
JOIN courses c ON c.active = true AND (
  (substring(trim(v.focus) from '^([A-Z]{2,}[0-9]+) ') IS NOT NULL AND c.course_code = substring(trim(v.focus) from '^([A-Z]{2,}[0-9]+) '))
  OR
  (substring(trim(v.focus) from '^([A-Z]{2,}[0-9]+) ') IS NULL AND c.course_name = trim(v.focus))
)
ON CONFLICT (tutor_id, course_id, instructor) DO NOTHING;
`

  fs.writeFileSync(OUT_PATH, sql, 'utf8')
  console.log('Wrote', tutors.length, 'tutors and', pairs.length, 'tutor–course links to', OUT_PATH)
}

main()
