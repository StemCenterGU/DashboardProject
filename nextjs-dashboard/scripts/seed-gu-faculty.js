/**
 * Generate SQL seed for GU faculty only (STEM dashboard).
 * Reads database/gu-faculty-raw.txt (one line: Name (Dept): USERID,Name (Dept): USERID,...).
 * Run from nextjs-dashboard root: node scripts/seed-gu-faculty.js
 * Run migration-gu-faculty.sql first if faculty table does not exist.
 * Then run database/seed-gu-faculty.sql in Supabase SQL Editor.
 */

const fs = require('fs')
const path = require('path')

const DATA_DIR = path.join(__dirname, '..', 'database')
const FACULTY_PATH = path.join(DATA_DIR, 'gu-faculty-raw.txt')
const OUT = path.join(DATA_DIR, 'seed-gu-faculty.sql')

function parseFaculty(raw) {
  if (!raw || !raw.trim()) return []
  return raw
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((item) => {
      const match = item.match(/^(.+?)\s*\(([^)]*)\)\s*:\s*(\S+)\s*$/)
      if (match) {
        return {
          name: match[1].trim().replace(/'/g, "''"),
          department: match[2].trim().replace(/'/g, "''"),
          userId: match[3].trim(),
        }
      }
      return { name: item.replace(/'/g, "''"), department: '', userId: '' }
    })
}

function main() {
  let raw
  try {
    raw = fs.readFileSync(FACULTY_PATH, 'utf8')
  } catch (e) {
    console.error('Missing', FACULTY_PATH)
    console.error('Add gu-faculty-raw.txt with one line: Name (Dept): USERID,...')
    process.exit(1)
  }
  const faculty = parseFaculty(raw)
  console.log('Parsed', faculty.length, 'faculty.')
  const lines = faculty.map(
    (f) => `  ('${f.name}', ${f.department ? `'${f.department}'` : 'NULL'}, ${f.userId ? `'${f.userId}'` : 'NULL'})`
  )
  const sql = `-- GU faculty seed (generated by scripts/seed-gu-faculty.js)
-- Run migration-gu-faculty.sql first if faculty table does not exist.
INSERT INTO faculty (name, department, user_id)
VALUES
${lines.join(',\n')}
ON CONFLICT (user_id) DO UPDATE SET
  name = EXCLUDED.name,
  department = EXCLUDED.department,
  updated_at = NOW();
`
  fs.writeFileSync(OUT, sql)
  console.log('Wrote', OUT)
}

main()
