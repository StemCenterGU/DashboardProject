/**
 * Generate SQL seed for GU courses only (STEM dashboard).
 * Reads database/gu-courses-raw.txt (one line: CODE (Name),CODE (Name),...).
 * Run from nextjs-dashboard root: node scripts/seed-gu-courses.js
 * Then run database/seed-gu-courses.sql in Supabase SQL Editor.
 */

const fs = require('fs')
const path = require('path')

const DATA_DIR = path.join(__dirname, '..', 'database')
const COURSES_PATH = path.join(DATA_DIR, 'gu-courses-raw.txt')
const OUT = path.join(DATA_DIR, 'seed-gu-courses.sql')

function parseCourses(raw) {
  if (!raw || !raw.trim()) return []
  return raw
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((item) => {
      const match = item.match(/^([A-Z0-9_]+)\s*\((.+)\)\s*$/)
      if (match) return { code: match[1].trim(), name: match[2].trim().replace(/'/g, "''") }
      return { code: item.replace(/'/g, "''"), name: item.replace(/'/g, "''") }
    })
}

function main() {
  let raw
  try {
    raw = fs.readFileSync(COURSES_PATH, 'utf8')
  } catch (e) {
    console.error('Missing', COURSES_PATH)
    console.error('Add gu-courses-raw.txt with one line: CODE (Name),CODE (Name),...')
    process.exit(1)
  }
  const courses = parseCourses(raw)
  console.log('Parsed', courses.length, 'courses.')
  const lines = courses.map((c) => `  ('${c.code}', '${c.name}', true)`)
  const sql = `-- GU courses seed (generated by scripts/seed-gu-courses.js)
INSERT INTO courses (course_code, course_name, active)
VALUES
${lines.join(',\n')}
ON CONFLICT (course_code) DO UPDATE SET
  course_name = EXCLUDED.course_name,
  active = EXCLUDED.active,
  updated_at = NOW();
`
  fs.writeFileSync(OUT, sql)
  console.log('Wrote', OUT)
}

main()
